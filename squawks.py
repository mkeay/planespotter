# How many owners to name before giving up and saying "and others", and
# how much of the IRC line the whole annotation may eat. Alerts already
# run long, and the tracking link is at the far end of them.
MAX_OWNERS = 3
MAX_LENGTH = 52


def purpose(code):
    """The published reason for a squawk, or the unit that controls it --
    "0036" -> "helicopter pipeline/powerline inspection", "5271" ->
    "transit code, Channel Islands", "0421" -> "Farnborough Radar / RAF
    Leeming / Ireland Domestic ...".

    None for anything that isn't four octal digits, and None for the
    handful of codes with no allocation at all, so callers can simply
    skip the annotation."""
    if not code or not _CODE_RE.match(code):
        return None
    if code in MEANINGS:
        return MEANINGS[code]

    matches = [(int(high, 8) - int(low, 8), what)
               for low, high, what in RANGES if low <= code <= high]
    matches.sort(key=lambda m: m[0])
    owners, kept = [], 0
    for _, what in matches:
        if what in owners:
            continue
        owners.append(what)
        if kept < MAX_OWNERS and len(" / ".join(owners[:kept + 1])) <= MAX_LENGTH:
            kept += 1
    if not owners:
        return None
    kept = max(1, kept)  # one name, however long, beats none
    text = " / ".join(owners[:kept])
    return text + " and others" if len(owners) > kept else text
